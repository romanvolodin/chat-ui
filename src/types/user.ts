import type { UserId } from './ids'

/**
 * Запись справочника пользователей.
 *
 * Автором сообщения может быть человек, канал, бот или администратор: для интерфейса
 * все они одинаковые записи справочника.
 */
export interface User {
  id: UserId
  name: string
  /** Адрес картинки аватара. Если не задан, интерфейс рисует текстовый аватар с инициалами. */
  avatar?: string
  /** Нужен для сообщения-контакта. */
  phone?: string
  /** Пользователь заблокирован. Признак один на все чаты, его сообщения показываются свёрнутыми. */
  isBlocked?: boolean
  /** Пользователь сейчас в сети. */
  isOnline?: boolean
  /** Момент последней активности (дата и время), из него собирается строка «был в сети …». */
  lastActiveAt?: Date
  /** Показывать пометку «Бот». */
  isBot?: boolean
}

/**
 * Справочник пользователей: записи по id.
 *
 * Если автора из сообщения в справочнике нет, интерфейс показывает заглушку
 * («Неизвестный пользователь», пустой аватар).
 */
export type UserDirectory = Record<UserId, User>
